const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');

const base = process.env.SONG_BETA_TEST_URL;
if (!base || !/^http:\/\/(127\.0\.0\.1|localhost):\d+\/mygrain\/$/.test(base)) throw new Error('Use an isolated localhost test server.');

(async () => {
    const browser = await chromium.launch({ executablePath: '/snap/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--autoplay-policy=no-user-gesture-required'] });
    const errors = [];
    const writes = [];
    const configure = async page => {
        page.on('pageerror', error => errors.push(error.message));
        await page.route('https://openclaw.blackcarburning.com/**', route => {
            if (!['GET', 'HEAD'].includes(route.request().method())) { writes.push(route.request().url()); return route.abort(); }
            return route.continue();
        });
    };
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        const page = await context.newPage();
        await configure(page);
        await page.goto(base, { waitUntil: 'load' });
        await page.waitForFunction(() => window.mygrainVocalTakes && window.mygrainSongBeta && !mygrainSongBeta.busy);
        await page.click('#start-btn');
        await page.waitForFunction(() => isAudioGraphReady() && !engineStarting && !stateSaveSuspended);
        const setup = await page.evaluate(async () => {
            stopAllPerformancePlayback({ silent: true });
            document.getElementById('globalBpmSlider').value = '300';
            document.getElementById('globalBpmSlider').dispatchEvent(new Event('input', { bubbles: true }));
            syncPatternLengthControls(8);
            setLoopLayerSolo('none', { silent: true, skipSave: true });
            for (const layer of SPARSE_RANDOM_LAYER_DEFINITIONS) layer.setEnabled(false, { silent: true, skipSave: true });
            setDrumMachineEnabled(false, { silent: true, skipSave: true });
            setFxMuted(true, { silent: true });
            resetFinalPanLab();
            const makeBuffer = frequency => {
                const buffer = audioContext.createBuffer(1, Math.round(audioContext.sampleRate * .4), audioContext.sampleRate);
                const data = buffer.getChannelData(0);
                for (let frame = 0; frame < data.length; frame += 1) data[frame] = Math.sin(2 * Math.PI * frequency * frame / buffer.sampleRate) * .3;
                return buffer;
            };
            await applyRecordedBastardLoopMBuffer(makeBuffer(220), { bpm: 300 });
            await applyRecordedBastardLoopMPlusBuffer(makeBuffer(330), { bpm: 300 });
            const originalLead = bastardLoopMRawBuffer;
            const originalBacking = bastardLoopMPlusRawBuffer;
            randomizeMegaBastardLoopSettings();
            const chooseLayers = chooseSparseRandomLayerSelection;
            chooseSparseRandomLayerSelection = () => SPARSE_RANDOM_LAYER_DEFINITIONS.filter(layer => ['bastardm', 'bastardmplus', 'bastarda', 'bastardx'].includes(layer.key));
            try { applySparseRandomLayerSelection({ silent: true }); }
            finally { chooseSparseRandomLayerSelection = chooseLayers; }
            const randomRetained = originalLead === bastardLoopMRawBuffer && originalBacking === bastardLoopMPlusRawBuffer && bastardLoopMPlusEnabled;
            setDrumMachineEnabled(false, { silent: true, skipSave: true });
            setBastardLoopMEnabled(true, { silent: true, skipSave: true });
            setBastardLoopMPlusEnabled(true, { silent: true, skipSave: true });
            setBastardLoopMLevelPercent(45);
            setBastardLoopMPlusLevelPercent(31);
            setLoopLayerSolo('bastardmplus', { silent: true, skipSave: true });
            const soloIndependent = getBastardLoopMLevelValue() === 0 && getBastardLoopMPlusLevelValue() === .31;
            setLoopLayerSolo('none', { silent: true, skipSave: true });
            const started = startAllBastardLoopLayers(audioContext.currentTime + .1, { skipUi: true });
            const result = { started, randomRetained, soloIndependent, independent: bastardLoopMSource !== bastardLoopMPlusSource && bastardLoopMSource.buffer !== bastardLoopMPlusSource.buffer, lead: Array.from(bastardLoopMRawBuffer.getChannelData(0).slice(0, 50)), backing: Array.from(bastardLoopMPlusRawBuffer.getChannelData(0).slice(0, 50)) };
            stopAllBastardLoopLayers({ skipUi: true, fade: false });
            return result;
        });
        assert.equal(setup.started, true);
        assert.equal(setup.independent, true);
        assert.equal(setup.randomRetained, true);
        assert.equal(setup.soloIndependent, true);
        await page.click('#performanceBastardLoopMSaveVersionBtn');
        await page.waitForFunction(() => !mygrainVocalTakes.busy);
        await page.fill('#vocalTakesDialog [data-field="new-user"]', 'M+ Test Vocalist');
        await page.click('#vocalTakesDialog [data-action="create-user"]');
        await page.waitForFunction(() => !mygrainVocalTakes.busy && mygrainVocalTakes.selectedUser());
        await page.fill('#vocalTakesDialog [data-field="name"]', 'Lead take');
        await page.click('#vocalTakesDialog [data-action="save"]');
        await page.waitForFunction(() => !mygrainVocalTakes.busy && mygrainVocalTakes.takes.length === 1);
        const lead = await page.evaluate(() => mygrainVocalTakes.takes[0]);
        await page.click('#vocalTakesDialog [data-action="close"]');
        await page.click('#performanceBastardLoopMPlusSaveVersionBtn');
        await page.waitForFunction(() => !mygrainVocalTakes.busy && mygrainVocalTakes.targetLane === 'M+');
        assert.match(await page.locator('#vocalTakesDialog [data-target]').textContent(), /M\+.*backing/);
        await page.fill('#vocalTakesDialog [data-field="new-folder"]', 'Harmonies');
        await page.click('#vocalTakesDialog [data-action="create-folder"]');
        await page.waitForFunction(() => !mygrainVocalTakes.busy && mygrainVocalTakes.folderId);
        await page.fill('#vocalTakesDialog [data-field="name"]', 'Backing take');
        await page.click('#vocalTakesDialog [data-action="save"]');
        await page.waitForFunction(() => !mygrainVocalTakes.busy && mygrainVocalTakes.takes.length === 2);
        const backing = await page.evaluate(() => mygrainVocalTakes.takes.find(take => take.name === 'Backing take'));
        await page.selectOption('#vocalTakesDialog [data-field="folder"]', '');
        page.once('dialog', dialog => { assert.match(dialog.message(), /into M\+/); return dialog.accept(); });
        await page.locator(`[data-take-id="${lead.id}"] [data-load-take]`).click();
        await page.waitForFunction(() => !mygrainVocalTakes.busy && document.querySelector('#vocalTakesDialog [data-status]').textContent.includes('into M+'));
        const loaded = await page.evaluate(() => ({ lead: Array.from(bastardLoopMRawBuffer.getChannelData(0).slice(0, 50)), backing: Array.from(bastardLoopMPlusRawBuffer.getChannelData(0).slice(0, 50)) }));
        assert.deepEqual(loaded.lead, setup.lead);
        assert.ok(loaded.backing.every((value, index) => Math.abs(value - setup.lead[index]) < .00006));
        await page.selectOption('#vocalTakesDialog [data-field="folder"]', backing.folderId);
        page.once('dialog', dialog => dialog.accept());
        await page.locator(`[data-take-id="${backing.id}"] [data-load-take]`).click();
        await page.waitForFunction(() => !mygrainVocalTakes.busy);
        await page.click('#vocalTakesDialog [data-action="close"]');
        await page.evaluate(() => {
            setBastardLoopMEnabled(false, { silent: true });
            setBastardLoopMPlusEnabled(true, { silent: true });
            document.getElementById('performanceBastardLoopMPlusSemitone').value = '-3';
            document.getElementById('performanceBastardLoopMPlusSemitone').dispatchEvent(new Event('input', { bubbles: true }));
            document.getElementById('performanceBastardLoopMPlusDelayMix').value = '17';
            document.getElementById('performanceBastardLoopMPlusDelayMix').dispatchEvent(new Event('input', { bubbles: true }));
            setBastardLoopMPlusInputGainPercent(0);
            saveState({ force: true });
        });
        await page.fill('#songBetaName', 'M+ isolated song');
        await page.click('#songBetaNewSong');
        await page.waitForFunction(() => !mygrainSongBeta.busy && mygrainSongBeta.song);
        await page.fill('#songBetaPartName', 'Backing only');
        await page.click('#songBetaNewPart');
        await page.waitForFunction(() => !mygrainSongBeta.busy && mygrainSongBeta.song.parts.length === 1);
        const recall = await page.evaluate(async () => {
            const controller = mygrainSongBeta;
            const part = await controller.loadPart(controller.song.parts[0]);
            window.mPlusSavedPart = part;
            window.mPlusLibraryIds = mygrainVocalTakes.takes.map(take => take.id);
            document.getElementById('performanceBastardLoopMPlusSemitone').value = '12';
            document.getElementById('performanceBastardLoopMPlusSemitone').dispatchEvent(new Event('input', { bubbles: true }));
            setBastardLoopMPlusLevelPercent(90);
            mygrainSongBetaAdapter.recall(part, { start: false });
            const result = { assets: part.snapshot.assets.map(asset => asset.key), pitch: bastardLoopMPlusPitchSemitones, level: bastardLoopMPlusLevel, inputGain: bastardLoopMPlusInputGain, delay: bastardLoopMPlusDelayMix, lead: Array.from(bastardLoopMRawBuffer.getChannelData(0).slice(0, 50)), backing: Array.from(bastardLoopMPlusRawBuffer.getChannelData(0).slice(0, 50)), independent: bastardLoopMRawBuffer !== bastardLoopMPlusRawBuffer };
            const silent = JSON.parse(JSON.stringify(part.snapshot));
            silent.state.modes.bastardLoopMPlusLevel = 0;
            silent.state.sliders.performanceBastardLoopMPlusLevel = '0';
            silent.state.sliders.performanceBastardLoopMPlusLevelMixer = '0';
            mygrainSongBetaAdapter.recall({ snapshot: silent, buffers: part.buffers }, { start: false });
            result.zeroLevel = bastardLoopMPlusLevel;
            mygrainSongBetaAdapter.recall(part, { start: false });
            return result;
        });
        for (const key of ['bastardM', 'bastardMRender', 'bastardMPlus', 'bastardMPlusRender']) assert.ok(recall.assets.includes(key));
        assert.equal(recall.pitch, -3);
        assert.equal(recall.level, .31);
        assert.equal(recall.inputGain, 0);
        assert.equal(recall.delay, .17);
        assert.equal(recall.independent, true);
        assert.equal(recall.zeroLevel, 0);
        await page.click('#songBetaArm');
        await page.waitForFunction(() => mygrainSongBeta.armed && !mygrainSongBeta.busy, null, { timeout: 120000 });
        const rendered = await page.evaluate(async () => {
            const part = mygrainSongBeta.song.parts[0];
            const render = await mygrainSongBeta.loadRender(part);
            let energy = 0;
            for (const sample of render.getChannelData(0)) energy += sample * sample;
            return { duration: render.duration, rms: Math.sqrt(energy / render.length) };
        });
        assert.ok(Math.abs(rendered.duration - .4) < .001);
        assert.ok(rendered.rms > .001, `M+ frozen render silent: ${rendered.rms}`);
        await page.click('#songBetaPlay');
        await page.waitForFunction(() => mygrainSongBeta.playing);
        await page.waitForFunction(() => !mygrainSongBeta.playing, null, { timeout: 15000 });
        const legacy = await page.evaluate(() => {
            const snapshot = JSON.parse(JSON.stringify(mPlusSavedPart.snapshot));
            for (const key of Object.keys(snapshot.state.modes)) if (key.startsWith('bastardLoopMPlus')) delete snapshot.state.modes[key];
            for (const group of ['sliders', 'selects']) for (const key of Object.keys(snapshot.state[group] || {})) if (key.startsWith('performanceBastardLoopMPlus')) delete snapshot.state[group][key];
            snapshot.extra.controls = snapshot.extra.controls.filter(control => !control.id.startsWith('performanceBastardLoopMPlus'));
            delete snapshot.extra.metadata.bastardMPlus;
            snapshot.assets = snapshot.assets.filter(asset => !asset.key.startsWith('bastardMPlus'));
            const buffers = new Map([...mPlusSavedPart.buffers].filter(([key]) => !key.startsWith('bastardMPlus')));
            mygrainSongBetaAdapter.recall({ snapshot, buffers }, { start: false });
            return { empty: !bastardLoopMPlusRawBuffer && !bastardLoopMPlusBuffer, enabled: bastardLoopMPlusEnabled, pitch: bastardLoopMPlusPitchSemitones, delay: bastardLoopMPlusDelayMix, library: mygrainVocalTakes.takes.map(take => take.id) };
        });
        assert.equal(legacy.empty, true);
        assert.equal(legacy.enabled, false);
        assert.equal(legacy.pitch, 0);
        assert.equal(legacy.delay, 0);
        assert.deepEqual(legacy.library.sort(), [lead.id, backing.id].sort());
        const patch = await page.evaluate(async () => {
            mygrainSongBetaAdapter.recall(mPlusSavedPart, { start: false });
            syncPatternLengthControls(16);
            setBastardLoopMPlusEnabled(false, { silent: true });
            setBastardLoopMPlusPreserveDuration(false, { silent: true });
            setBastardLoopMPlusReverse(true, { silent: true });
            setSelectValue('performanceBastardLoopMPlusFilterMode', 'highpass-24');
            setSelectValue('performanceBastardLoopMPlusDelayDivision', '1d');
            const blob = await buildPatchZipBlob('mplus-isolated.zip');
            const bytes = await blob.arrayBuffer();
            const entries = parseStoredZipEntries(bytes);
            const manifest = JSON.parse(getZipText(entries, 'song-part.json') || getZipText(entries, 'manifest.json'));
            await clearBastardLoopMPlus();
            setBastardLoopMPlusEnabled(true, { silent: true });
            setBastardLoopMPlusPreserveDuration(true, { silent: true });
            setBastardLoopMPlusReverse(false, { silent: true });
            setSelectValue('performanceBastardLoopMPlusFilterMode', 'lowpass-48');
            setSelectValue('performanceBastardLoopMPlusDelayDivision', '2');
            await openPatchZipFromArrayBuffer(bytes, 'mplus-isolated.zip');
            return { keys: manifest.assets.map(asset => asset.key), frames: bastardLoopMPlusRawBuffer?.length, enabled: bastardLoopMPlusEnabled, preserve: bastardLoopMPlusPreserveDuration, reverse: bastardLoopMPlusReverse, filter: bastardLoopMPlusFilterMode, division: bastardLoopMPlusDelayDivision };
        });
        assert.ok(patch.keys.includes('bastardMPlus'));
        assert.ok(patch.frames > 1000);
        assert.equal(patch.enabled, false);
        assert.equal(patch.preserve, false);
        assert.equal(patch.reverse, true);
        assert.equal(patch.filter, 'highpass-24');
        assert.equal(patch.division, '1d');
        const recording = await page.evaluate(async () => {
            stopAllPerformancePlayback({ silent: true });
            syncPatternLengthControls(8);
            setBastardLoopMEnabled(true, { silent: true });
            setBastardLoopMPlusEnabled(true, { silent: true });
            setBastardLoopMPlusInputGainPercent(100);
            document.getElementById('performanceBastardLoopMPlusSemitone').value = '0';
            document.getElementById('performanceBastardLoopMPlusSemitone').dispatchEvent(new Event('input', { bubbles: true }));
            const destination = audioContext.createMediaStreamDestination();
            const oscillator = audioContext.createOscillator();
            const gain = audioContext.createGain();
            oscillator.frequency.value = 440;
            gain.gain.value = .15;
            oscillator.connect(gain).connect(destination);
            oscillator.start();
            window.mPlusFakeMic = { oscillator, destination };
            navigator.mediaDevices.getUserMedia = async () => destination.stream;
            window.mPlusLeadBeforeRecording = Array.from(bastardLoopMRawBuffer.getChannelData(0).slice(0, 50));
            return beginBastardLoopMPlusRecording({ startFullLoop: true });
        });
        assert.equal(recording, true);
        await page.waitForFunction(() => bastardLoopMPlusRecordingState === 'idle' && bastardLoopMPlusRawBuffer, null, { timeout: 20000 });
        const mic = await page.evaluate(() => {
            mPlusFakeMic.oscillator.stop();
            const lead = Array.from(bastardLoopMRawBuffer.getChannelData(0).slice(0, 50));
            const buffer = bastardLoopMPlusRawBuffer;
            let peak = 0;
            for (const sample of buffer.getChannelData(0)) peak = Math.max(peak, Math.abs(sample));
            stopAllPerformancePlayback({ silent: true });
            saveState({ force: true });
            return { leadUnchanged: lead.every((value, index) => value === mPlusLeadBeforeRecording[index]), duration: buffer.duration, peak, bpm: bastardLoopMPlusSourceBpm };
        });
        assert.equal(mic.leadUnchanged, true);
        assert.ok(Math.abs(mic.duration - .4) < .01);
        assert.ok(mic.peak > .01);
        assert.equal(mic.bpm, 300);
        await page.reload({ waitUntil: 'load' });
        await page.click('#start-btn');
        await page.waitForFunction(() => isAudioGraphReady() && !engineStarting && !stateSaveSuspended && bastardLoopMPlusRawBuffer);
        assert.ok(Math.abs(await page.evaluate(() => bastardLoopMPlusRawBuffer.duration) - .4) < .01);
        for (const width of [390, 320]) {
            await page.setViewportSize({ width, height: 844 });
            await page.evaluate(() => document.getElementById('performanceBastardLoopMPlusTakesBtn').click());
            await page.waitForFunction(() => !mygrainVocalTakes.busy && document.getElementById('vocalTakesDialog').open);
            const layout = await page.evaluate(() => {
                const bounds = document.getElementById('vocalTakesDialog').getBoundingClientRect();
                return { left: bounds.left, right: bounds.right, width: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth + 1, target: mygrainVocalTakes.targetLane };
            });
            assert.ok(layout.left >= 0 && layout.right <= width + 1);
            assert.equal(layout.overflow, false);
            assert.equal(layout.target, 'M+');
            await page.click('#vocalTakesDialog [data-action="close"]');
        }
        await page.goto(base + 'manual.html', { waitUntil: 'load' });
        for (const id of ['song-mode', 'v-loop', 'm-loop', 'vocal-workflows', 'pan-lab']) assert.equal(await page.locator(`#${id}`).count(), 1);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
        assert.deepEqual(errors, []);
        assert.deepEqual(writes, []);
        console.log('PASS: Independent M/M+ playback, shared-library lane targets, song recall/cache/audio, legacy songs, patch ZIPs, microphone capture, reload and 390/320px layouts.');
        console.log(JSON.stringify({ rendered, mic }));
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
