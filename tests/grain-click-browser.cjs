// Native PCM regression for grain edges, not merely non-silent output.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium, webkit } = require('playwright-core');
const base = process.env.MYGRAIN_TEST_URL || 'http://127.0.0.1:18930/mygrain/';
assert.match(base, /^http:\/\/(127\.0\.0\.1|localhost):\d+\/mygrain\/$/);
const evidence = process.env.MYGRAIN_GRAIN_EVIDENCE || '/tmp/mygrain-grain-click';
fs.mkdirSync(evidence, { recursive: true });
(async () => {
 const results = [];
 for (const [engine, kind] of Object.entries({ chromium, webkit })) {
  const browser = await kind.launch(engine === 'chromium' ? { executablePath: '/snap/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage', '--autoplay-policy=no-user-gesture-required'] } : {});
  try {
   const context = await browser.newContext({ viewport: { width: 402, height: 874 }, isMobile: true, hasTouch: true });
   const registered = await context.request.post(base + 'api/auth/register', { data: { username: `click_${engine[0]}_${Date.now()}`, password: 'disposable-grain-click' } });
   assert.equal(registered.status(), 200);
   const page = await context.newPage(), errors = [];
   page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(45000);
   if (process.env.MYGRAIN_CLICK_BASELINE) await page.route(base, route => route.fulfill({ contentType: 'text/html', body: fs.readFileSync(process.env.MYGRAIN_CLICK_BASELINE, 'utf8') }));
   await page.goto(base); await page.waitForFunction(() => window.mygrainCardHistory && document.documentElement.dataset.mygrainStartup === 'ready');
   await page.evaluate(() => mygrainCardHistory.ready); await page.locator('#start-btn').tap();
   await page.waitForFunction(() => isAudioGraphReady() && !engineStarting && !stateSaveSuspended);
   for (const sampleRate of [44100, 48000]) for (const sizeMs of [10, 46, 80]) {
    const result = await page.evaluate(async ({ sampleRate, sizeMs }) => {
     stopAllPerformancePlayback({ silent: true });
     const online = audioContext, output = granularOutputGain;
     const sourceBuffer = online.createBuffer(1, sampleRate * 2, sampleRate);
     // DC is deliberate: every high-frequency component is generated by the
     // grain window, not by a pre-existing transient in the sample.
     sourceBuffer.getChannelData(0).fill(.3); grainASampleBuffer = sourceBuffer; grainBSampleBuffer = sourceBuffer;
     for (const [id, value] of Object.entries({ grainASampleLoopStart: 0, grainASampleLoopEnd: 100,
      grainAMicGrainPosition: 0, grainAMicGrainScale: 100, grainAMicGrainAttackScale: 100,
      grainAMicGrainReleaseScale: 100, grainAMicGrainLevel: 100, noiseMix: 0, panSpread: 0 })) {
      clearModulationForParam(id); document.getElementById(id).value = String(value);
     }
     const offline = new OfflineAudioContext(2, sampleRate, sampleRate);
     audioContext = offline; granularOutputGain = offline.createGain(); granularOutputGain.connect(offline.destination);
     const random = Math.random; Math.random = () => .5;
     try {
      const layer = { key: 'A', sourceMode: 'grainASample', sizeSeconds: sizeMs / 1000,
       startPct: 0, pitchRatio: 1, preserveDuration: true, attackSeconds: .04,
       decaySeconds: .095, releaseSeconds: 1.25, blend: sizeMs === 80 ? .30 : .21, smoothing: sizeMs === 80 ? .78 : .4,
       width: 0, panBias: 0, jitterSeconds: 0, volume: .4 };
      const interval = getGranularLayerIntervalSeconds(layer.sizeSeconds, layer.blend, layer.smoothing);
      const starts = [];
      for (let at = .04; at < .8; at += interval) {
       // Keep the hard real-source cap; this offline probe schedules at most 96 grains.
       if (starts.length >= 90) break;
       playGrain('C2', at, 1, { role: 'click-test', streamStartTime: .04, layerSettings: [layer] }); starts.push(at);
      }
      const rendered = await offline.startRendering(), pcm = rendered.getChannelData(0);
      const probe = new OfflineAudioContext(1, pcm.length, sampleRate), input = probe.createBuffer(1, pcm.length, sampleRate);
      input.copyToChannel(pcm, 0); const source = probe.createBufferSource(); source.buffer = input;
      let tail = source;
      for (let n = 0; n < 3; n++) { const hp = probe.createBiquadFilter(); hp.type = 'highpass'; hp.frequency.value = 3000; hp.Q.value = .707; tail.connect(hp); tail = hp; }
      tail.connect(probe.destination); source.start();
      const high = (await probe.startRendering()).getChannelData(0);
      let energy = 0, highEnergy = 0, maxSlope = 0, maxBend = 0, floor = Infinity;
      const lo = Math.round(sampleRate * .1), hi = Math.round(sampleRate * .5);
      for (let i = lo; i < hi; i++) { energy += pcm[i] ** 2; highEnergy += high[i] ** 2;
       maxSlope = Math.max(maxSlope, Math.abs(pcm[i] - pcm[i-1]));
       maxBend = Math.max(maxBend, Math.abs(pcm[i] - 2*pcm[i-1] + pcm[i-2])); floor = Math.min(floor, pcm[i]); }
      return { sampleRate, sizeMs, sources: starts.length, rms: Math.sqrt(energy/(hi-lo)),
       edgeNoiseDb: 10*Math.log10(highEnergy/energy), maxSlope, maxBend, floor, remaining: getConcurrentGrainSourceCount() };
     } finally { Math.random = random; audioContext = online; granularOutputGain = output; }
    }, { sampleRate, sizeMs });
    console.log(JSON.stringify({ engine, ...result }));
    assert.ok(result.rms > .005, 'Audible grain output');
    if (!process.env.MYGRAIN_CLICK_BASELINE) {
     assert.ok(result.edgeNoiseDb < (sizeMs === 10 ? -75 : -95), 'Grain edges must not add broadband crackle to a constant source');
     assert.ok(result.floor > .0001, 'Smoothing must not recreate gated silence');
     assert.equal(result.remaining, 0, 'Native sources must be cleaned up');
    }
    results.push({ engine, ...result });
   }
   assert.deepEqual(errors, []); await context.close();
  } finally { await browser.close(); }
 }
 fs.writeFileSync(`${evidence}/${process.env.MYGRAIN_CLICK_BASELINE ? 'baseline' : 'fixed'}-results.json`, JSON.stringify(results, null, 2));
})().catch(e => { console.error(e); process.exitCode = 1; });
